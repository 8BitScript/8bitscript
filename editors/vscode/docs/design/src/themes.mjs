// The CSS a webview gets besides colours.
const FONTS = {
  '--vscode-font-family': "-apple-system, BlinkMacSystemFont, 'Segoe UI', system-ui, sans-serif",
  '--vscode-font-size': '13px',
  '--vscode-font-weight': 'normal',
  '--vscode-editor-font-family': "Menlo, Monaco, 'Courier New', monospace",
  '--vscode-editor-font-size': '12px',
};

function readJsonc(path) {
  const text = readFileSync(path, 'utf8')
    .replace(/^\s*\/\/.*$/gm, '')
    .replace(/,(\s*[}\]])/g, '$1');
  return JSON.parse(text);
}

function colours(dir, file) {
  const doc = readJsonc(join(dir, file));
  const inherited = doc.include ? colours(dir, doc.include.replace(/^\.\//, '')) : {};
  return { ...inherited, ...(doc.colors ?? {}) };
}

export function themeCss(kind) {
  const merged = { ...DEFAULTS[kind], ...colours(THEME_DIR, FILES[kind]) };
  const lines = Object.keys(merged).sort().map((k) => `  --vscode-${k.replace(/\./g, '-')}: ${merged[k]};`);
  const fonts = Object.entries(FONTS).map(([k, v]) => `  ${k}: ${v};`);
  return `/* Generated by src/themes.mjs from ${FILES[kind]} (+ its includes) and the VS Code
   colour-registry defaults. ${Object.keys(merged).length} colours. Do not edit. */
:root {
  color-scheme: ${kind};
${fonts.join('\n')}
${lines.join('\n')}
}
`;
}

export function writeThemes(outDir) {
  for (const kind of Object.keys(FILES)) writeFileSync(join(outDir, `${kind}-modern.css`), themeCss(kind));
}
