// Dark Modern and Light Modern as the CSS custom properties VS Code injects
// into every webview (`--vscode-<colour-id with dots turned into dashes>`).
//
// The values come from the theme files that ship inside the editor
// (theme-defaults/themes/*.json, following their "include" chain). A theme file
// only lists the colours it overrides; everything else comes from VS Code's
// own colour registry, so DEFAULTS below repeats the registry values for the
// keys the prototype uses. The generated CSS is committed (themes/), so the
// prototypes render without an editor installed.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const THEME_DIR = process.env.DESIGN_THEME_DIR
  ?? '/Applications/Cursor.app/Contents/Resources/app/extensions/theme-defaults/themes';

const FILES = { dark: 'dark_modern.json', light: 'light_modern.json' };

